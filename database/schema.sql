
-- =========================================
-- GAMEHUB DATABASE SCHEMA
-- PostgreSQL / Supabase
-- =========================================

-- 1. USERS
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL,
    email VARCHAR(255) NOT NULL,
    password_hash TEXT NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'member'
        CHECK (role IN ('member', 'admin')),
    status VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'suspended')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower_unique
ON public.users (LOWER(username));

CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_unique
ON public.users (LOWER(email));


-- 2. GAMES
CREATE TABLE IF NOT EXISTS public.games (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    genre VARCHAR(100),
    year INTEGER,
    image TEXT,
    description TEXT,
    igdb_id BIGINT,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT games_year_check
        CHECK (year IS NULL OR year BETWEEN 1950 AND 2100)
);

-- รองรับฐานข้อมูลเดิมที่มีตาราง games อยู่แล้ว
ALTER TABLE public.games
ADD COLUMN IF NOT EXISTS igdb_id BIGINT;

CREATE UNIQUE INDEX IF NOT EXISTS games_igdb_id_key
ON public.games (igdb_id)
WHERE igdb_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS games_name_idx
ON public.games (name);

CREATE INDEX IF NOT EXISTS games_genre_idx
ON public.games (genre);

CREATE INDEX IF NOT EXISTS games_is_deleted_idx
ON public.games (is_deleted);


-- 3. PLATFORMS
CREATE TABLE IF NOT EXISTS public.platforms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

INSERT INTO public.platforms (name)
VALUES
    ('PC'),
    ('PlayStation'),
    ('Xbox'),
    ('Nintendo')
ON CONFLICT (name) DO NOTHING;


-- 4. GAME_PLATFORMS
CREATE TABLE IF NOT EXISTS public.game_platforms (
    game_id BIGINT NOT NULL REFERENCES public.games(id) ON DELETE CASCADE,
    platform_id BIGINT NOT NULL REFERENCES public.platforms(id) ON DELETE CASCADE,
    PRIMARY KEY (game_id, platform_id)
);

CREATE INDEX IF NOT EXISTS game_platforms_platform_id_idx
ON public.game_platforms (platform_id);


-- 5. GAME_RATINGS
CREATE TABLE IF NOT EXISTS public.game_ratings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    game_id BIGINT NOT NULL REFERENCES public.games(id) ON DELETE CASCADE,
    rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (user_id, game_id)
);

CREATE INDEX IF NOT EXISTS game_ratings_game_id_idx
ON public.game_ratings (game_id);


-- 6. GAME_REVIEWS
CREATE TABLE IF NOT EXISTS public.game_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    game_id BIGINT NOT NULL REFERENCES public.games(id) ON DELETE CASCADE,
    content TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'visible'
        CHECK (status IN ('visible', 'hidden')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (user_id, game_id),
    CONSTRAINT game_reviews_content_check
        CHECK (LENGTH(TRIM(content)) BETWEEN 1 AND 5000)
);

CREATE INDEX IF NOT EXISTS game_reviews_game_id_idx
ON public.game_reviews (game_id);

CREATE INDEX IF NOT EXISTS game_reviews_status_idx
ON public.game_reviews (status);


-- 7. USER_GAME_LIBRARY
CREATE TABLE IF NOT EXISTS public.user_game_library (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    game_id BIGINT NOT NULL REFERENCES public.games(id) ON DELETE CASCADE,
    status VARCHAR(30) NOT NULL DEFAULT 'want_to_play'
        CHECK (
            status IN (
                'want_to_play',
                'playing',
                'completed',
                'dropped'
            )
        ),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (user_id, game_id)
);

CREATE INDEX IF NOT EXISTS user_game_library_user_id_idx
ON public.user_game_library (user_id);


-- =========================================
-- AUTO UPDATE updated_at
-- =========================================

CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS users_updated_at ON public.users;
CREATE TRIGGER users_updated_at
BEFORE UPDATE ON public.users
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS games_updated_at ON public.games;
CREATE TRIGGER games_updated_at
BEFORE UPDATE ON public.games
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS game_ratings_updated_at ON public.game_ratings;
CREATE TRIGGER game_ratings_updated_at
BEFORE UPDATE ON public.game_ratings
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS game_reviews_updated_at ON public.game_reviews;
CREATE TRIGGER game_reviews_updated_at
BEFORE UPDATE ON public.game_reviews
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS user_game_library_updated_at ON public.user_game_library;
CREATE TRIGGER user_game_library_updated_at
BEFORE UPDATE ON public.user_game_library
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();


